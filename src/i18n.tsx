// ─── CONTEXT ────────────────────────────────────────────────────────────────
interface I18nContextType {
    lang: UILanguage;
    setLang: (lang: UILanguage) => void;
    t: (key: string, params?: Record<string, string | number>) => string;
    dir: 'ltr' | 'rtl';
}

const I18nContext = createContext<I18nContextType>({
    lang: 'en',
    setLang: () => { },
    t: (key) => key,
    dir: 'ltr',
});

// ─── PROVIDER ───────────────────────────────────────────────────────────────
export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
    const [lang, setLangState] = useState<UILanguage>(() => {
        try {
            const saved = localStorage.getItem('proads_ui_lang');
            if (saved === 'ar' || saved === 'en') return saved;
        } catch { }
        return 'en';
    });

    const setLang = useCallback((newLang: UILanguage) => {
        setLangState(newLang);
        try { localStorage.setItem('proads_ui_lang', newLang); } catch { }
        document.documentElement.dir = newLang === 'ar' ? 'rtl' : 'ltr';
        document.documentElement.lang = newLang;
    }, []);

    // Set dir on mount
    React.useEffect(() => {
        document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
        document.documentElement.lang = lang;
        try {
            if (!localStorage.getItem('proads_ui_lang')) { localStorage.setItem('proads_ui_lang', 'en'); }
        } catch (err) {
            // localStorage can throw in restricted contexts (private mode, blocked cookies) — non-fatal.
            console.warn('⚠️ i18n: unable to access localStorage for default UI language', err);
        }
    }, [lang]);

    const t = useCallback((key: string, params?: Record<string, string | number>): string => {
        let text = translations[lang]?.[key] || translations['en']?.[key] || key;
        if (params) {
            Object.entries(params).forEach(([k, v]) => {
                text = text.replace(`{${k}}`, String(v));
            });
        }
        return text;
    }, [lang]);

    const dir = lang === 'ar' ? 'rtl' : 'ltr';

    return (
        <I18nContext.Provider value={{ lang, setLang, t, dir }}>
            {children}
        </I18nContext.Provider>
    );
};

// ─── HOOK ───────────────────────────────────────────────────────────────────
export const useT = () => useContext(I18nContext);